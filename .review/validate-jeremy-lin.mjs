import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { join } from 'node:path';
import { evaluate } from './card-eval-lib.mjs';
import { runtime } from './reproduce.mjs';
const dir=new URL('./',import.meta.url), card=JSON.parse(await readFile(new URL('../public/cards/jeremy-lin-2011-12.json',dir),'utf8'));
const {PRESET_CARDS,applyCard}=await import(pathToFileURL(join(runtime,'src/engine/playerCard.mjs')).href);
assert.deepEqual(PRESET_CARDS.at(-1).card,card);
assert.equal(PRESET_CARDS.filter(x=>x.label.includes('Jeremy Lin')).length,2);
for(const keys of [['ra','paint','mid','c3','atb'],['cns','pullup','step','fade']])assert.ok(Math.abs(keys.reduce((s,k)=>s+card.ten[k],0)-100)<1e-9);
for(const rating of Object.values(card.r))assert.ok(Number.isInteger(rating)&&rating>=1&&rating<=99);
const p={...structuredClone(card),id:4242,name:'Original Player',age:28,tid:3,stats:[{year:2025}],con:{salary:4.2,years:2}};
const preserved=structuredClone({id:p.id,name:p.name,age:p.age,tid:p.tid,stats:p.stats,con:p.con});
assert.equal(applyCard(p,card,{}),'');
for(const k of Object.keys(preserved))assert.deepEqual(p[k],preserved[k]);
assert.ok(p.tenBase);assert.equal(p.cardPreset,25);
const target={min:940/35,pts:512/35,fga:383/35,tpa:75/35,fta:183/35,orb:18/35,drb:89/35,ast:216/35,stl:55/35,blk:9/35,tov:126/35,pf:78/35,fg:171/383,tp:24/75,ft:146/183};
const measured=evaluate(card,target,150,14000001,3);
const tolerances={pts:1.5,fga:1.2,tpa:.5,fta:.8,orb:.3,drb:.6,ast:.8,stl:.35,blk:.25,tov:.6,pf:.5,fg:.035,tp:.04,ft:.035};
for(const [k,tolerance]of Object.entries(tolerances))assert.ok(Math.abs(measured[k]-target[k])<=tolerance,k+' outside diagnostic tolerance: '+measured[k]+' vs '+target[k]);
const report={target,measured,overall:p.ovr,potential:p.pot,contexts:3,styles:2,games:900,minutesNormalized:true,source:card.sources,card};
await writeFile(new URL('jeremy-lin-validation.json',dir),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));console.log('Jeremy Lin card import, identity preservation, preset append and 900-game diagnostic checks passed.');
